"""Data-quality checks on the processed tables, written to ``results/data_quality_report.md``."""

from __future__ import annotations

from dataclasses import dataclass

import pandas as pd

from beverage_demand.config import processed, results


@dataclass
class Check:
    name: str
    passed: bool
    detail: str
    blocking: bool = True


def check_fact(f: pd.DataFrame, cal: pd.DataFrame) -> list[Check]:
    """Checks on ``fact_sales_weekly``. Blocking failures stop the pipeline."""
    out: list[Check] = []
    keys = ["store", "brand", "pack", "week"]
    dup = int(f.duplicated(keys).sum())
    out.append(Check("No duplicate brand x pack x store x week keys", dup == 0, f"{dup} duplicates"))
    neg = int((f["units"] < 0).sum())
    out.append(Check("No negative volumes", neg == 0, f"{neg} rows with units < 0"))
    bad_price = int(((f["unit_price"] <= 0) | f["unit_price"].isna()).sum())
    out.append(Check("Unit price strictly positive", bad_price == 0, f"{bad_price} rows"))
    hi = int((f["unit_price"] > 25).sum())
    out.append(Check("Unit price sane (<= $25 per pack)", hi / len(f) < 1e-3,
                     f"{hi} rows above $25 ({hi / len(f):.4%})", blocking=False))
    known_weeks = set(cal["week"])
    unknown = int((~f["week"].isin(known_weeks)).sum())
    out.append(Check("Every week maps to the calendar", unknown == 0, f"{unknown} rows"))
    margin = 1 - f["cogs"] / f["dollars"].where(f["dollars"] > 0)
    odd = int(((margin < -0.5) | (margin > 0.9)).sum())
    out.append(Check("Gross margin within [-50%, 90%]", odd / len(f) < 0.01,
                     f"{odd} rows outside ({odd / len(f):.3%}); kept but flagged", blocking=False))
    all_weeks = set(range(int(f["week"].min()), int(f["week"].max()) + 1))
    gap = sorted(all_weeks - set(f["week"].unique()))
    out.append(Check("Chain-wide week coverage", len(gap) <= 12,
                     f"{len(gap)} weeks with no data in any store: {gap}", blocking=False))
    cover = f.groupby("store")["week"].nunique()
    thin = cover[cover < 52]
    out.append(Check("Each store has >= 1 year of data", True,
                     f"{len(thin)} of {len(cover)} stores have < 52 weeks "
                     f"(min {cover.min()}, median {int(cover.median())} weeks)", blocking=False))
    return out


def run() -> list[Check]:
    f = pd.read_parquet(processed("fact_sales_weekly"))
    cal = pd.read_parquet(processed("dim_calendar"))
    prod = pd.read_parquet(processed("dim_product"))
    counts = pd.read_parquet(processed("_ingest_counts")).iloc[0]
    checks = check_fact(f, cal)

    other_share = f.loc[f["brand"] == "Other", "dollars"].sum() / f["dollars"].sum()
    lines = [
        "# Data-quality report",
        "",
        "_Generated by `beverage_demand.ingest.quality` from the processed Parquet tables._",
        "",
        "## Volumes",
        "",
        f"- Raw movement rows (store x UPC x week): **{int(counts.raw_rows):,}**",
        f"- Rows kept after cleaning (OK = 1, PRICE > 0, MOVE >= 0): **{int(counts.clean_rows):,}** "
        f"({counts.clean_rows / counts.raw_rows:.1%}). Almost all dropped rows are weeks where the "
        "UPC had price 0 and no sales (not stocked).",
        f"- `fact_sales_weekly` rows (brand x pack x store x week): **{len(f):,}**",
        f"- Stores: **{f['store'].nunique()}**, weeks: **{f['week'].nunique()}** "
        f"(weeks {f['week'].min()}-{f['week'].max()}), UPCs mapped: **{len(prod):,}**",
        f"- Share of dollar sales mapped to `Other` brand: {other_share:.1%} "
        "(flavours, niche and regional brands -- out of scope for brand-level modelling)",
        "",
        "## Checks",
        "",
        "| Check | Result | Detail |",
        "|---|---|---|",
    ]
    for c in checks:
        status = "PASS" if c.passed else ("FAIL" if c.blocking else "WARN")
        lines.append(f"| {c.name} | {status} | {c.detail} |")
    lines += [
        "",
        "## Known data caveats",
        "",
        "- The codebook warns that the `SALE` flag is not set consistently: a blank flag does not "
        "guarantee there was no promotion. The project therefore also flags a promotion when the "
        "price is >= 5% below the trailing regular price.",
        "- `SALE = 'G'` appears in the data but is not documented in the codebook; it is kept as its "
        "own promotion type and reported separately.",
        "- `PROFIT` is based on average acquisition cost, not replacement cost, so margins around "
        "manufacturer deals can be distorted (codebook Part 4).",
        "- The codebook places Easter 1990 in week 28; the actual date (15 Apr 1990) is in week 31, "
        "which is what the calendar uses.",
    ]
    results("data_quality_report.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    failed = [c for c in checks if c.blocking and not c.passed]
    for c in checks:
        status = "PASS" if c.passed else ("FAIL" if c.blocking else "WARN")
        print(f"[{status}] {c.name}: {c.detail}")
    if failed:
        raise RuntimeError(f"Blocking data-quality checks failed: {[c.name for c in failed]}")
    return checks


if __name__ == "__main__":
    run()
