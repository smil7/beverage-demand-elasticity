"""Run the SQL data-quality checks (``sql/quality/checks.sql``) and write a short report."""

from __future__ import annotations

import duckdb
import pandas as pd

from beverage_demand.config import results
from beverage_demand.db import connect, query, query_file


def run_checks(con: duckdb.DuckDBPyConnection) -> pd.DataFrame:
    """One row per check with a PASS / WARN / FAIL status."""
    checks = query_file(con, "quality/checks.sql")
    total = con.execute("SELECT COUNT(*) FROM fact_sales_weekly").fetchone()[0]
    share = checks["failing_rows"] / max(total, 1)
    ok = (checks["failing_rows"] == 0) | (share <= checks["max_share"])
    checks["status"] = ["PASS" if o else ("FAIL" if b else "WARN")
                        for o, b in zip(ok, checks["blocking"], strict=True)]
    checks["share"] = share
    return checks


def run() -> pd.DataFrame:
    with connect(read_only=True) as con:
        checks = run_checks(con)
        log = query(con, "SELECT * FROM etl_run_log ORDER BY loaded_at DESC LIMIT 1").iloc[0]
        facts = query(con, """
            SELECT COUNT(DISTINCT store) AS stores, COUNT(DISTINCT week) AS weeks,
                   MIN(week) AS first_week, MAX(week) AS last_week,
                   SUM(dollars) FILTER (WHERE brand = 'Other') / SUM(dollars) AS other_share
            FROM fact_sales_weekly""").iloc[0]
        n_upc = con.execute("SELECT COUNT(*) FROM dim_product").fetchone()[0]

    lines = [
        "# Data-quality report",
        "",
        "_Generated by `beverage_demand.ingest.quality` from `sql/quality/checks.sql`._",
        "",
        "## Volumes",
        "",
        f"- Raw movement rows (store x UPC x week): **{int(log.raw_rows):,}**",
        f"- Rows kept after cleaning (OK = 1, PRICE > 0, MOVE >= 0): **{int(log.clean_rows):,}** "
        f"({log.clean_rows / log.raw_rows:.1%}). Almost all dropped rows are weeks where the UPC "
        "had price 0 and no sales (not stocked).",
        f"- `fact_sales_weekly` rows (brand x pack x store x week): **{int(log.fact_rows):,}**",
        f"- Stores: **{int(facts.stores)}**, weeks with data: **{int(facts.weeks)}** "
        f"(weeks {int(facts.first_week)}-{int(facts.last_week)}), UPCs mapped: **{n_upc:,}**",
        f"- Share of dollar sales mapped to `Other` brand: {facts.other_share:.1%} "
        "(flavours, niche and regional brands)",
        "",
        "## Checks",
        "",
        "| Check | Result | Failing rows | Detail |",
        "|---|---|---|---|",
    ]
    for c in checks.itertuples():
        lines.append(f"| {c.check_name} | {c.status} | {c.failing_rows:,} ({c.share:.2%}) | {c.detail} |")
    lines += [
        "",
        "## Known data caveats",
        "",
        "- The codebook warns that the `SALE` flag is not set consistently, so a promotion is also "
        "flagged when the price is >= 5% below the regular price.",
        "- `SALE = 'G'` appears in the data but is not documented in the codebook; it is kept as its "
        "own promotion type.",
        "- `PROFIT` is based on average acquisition cost, so margins around manufacturer deals can be "
        "distorted (codebook Part 4).",
        "- The codebook places Easter 1990 in week 28; the actual date (15 Apr 1990) is in week 31, "
        "which is what the calendar uses.",
    ]
    results("data_quality_report.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    for c in checks.itertuples():
        print(f"[{c.status}] {c.check_name}: {c.failing_rows:,} failing {c.detail}")
    if (checks["status"] == "FAIL").any():
        raise RuntimeError("Blocking data-quality checks failed")
    return checks


if __name__ == "__main__":
    run()
